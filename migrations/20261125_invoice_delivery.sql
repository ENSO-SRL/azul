-- Additive migration. Existing payment/booking invoices are not rewritten.
CREATE SCHEMA IF NOT EXISTS pagos;
CREATE TABLE IF NOT EXISTS pagos.invoices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id varchar(36) NOT NULL UNIQUE,
    invoice_number varchar(80) UNIQUE,
    customer_id varchar(100) NOT NULL,
    currency varchar(3) NOT NULL,
    subtotal integer NOT NULL, itbis integer NOT NULL, total integer NOT NULL,
    balance_due integer NOT NULL DEFAULT 0,
    issued_at timestamptz NOT NULL,
    document_json text NOT NULL, html_content text NOT NULL,
    pdf_content bytea NOT NULL, pdf_sha256 varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT invoice_amounts_valid CHECK (total > 0 AND subtotal >= 0 AND itbis >= 0
        AND subtotal + itbis = total AND balance_due = 0)
);
CREATE TABLE IF NOT EXISTS pagos.invoice_email_outbox (
    id varchar(100) PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES pagos.invoices(id),
    scope varchar(255) NOT NULL, audience varchar(20) NOT NULL, recipient varchar(255) NOT NULL,
    payload_json text NOT NULL DEFAULT '{}',
    status varchar(20) NOT NULL DEFAULT 'PENDING', attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(), lease_until timestamptz,
    lease_token varchar(36) NOT NULL DEFAULT '', provider_id varchar(255) NOT NULL DEFAULT '',
    last_error varchar(100) NOT NULL DEFAULT '', updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(invoice_id, recipient)
);
CREATE INDEX IF NOT EXISTS ix_invoice_email_due ON pagos.invoice_email_outbox(scope,status,next_attempt_at);
